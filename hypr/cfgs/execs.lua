local defaults = require("cfgs.defaults")

hl.on("hyprland.start", function()
	hl.exec_cmd("/usr/libexec/hyprpolkitagent")
	hl.exec_cmd("pkill -u $USER -x pipewire || true && sleep 1 && gentoo-pipewire-launcher")
	hl.exec_cmd("dbus-update-activation-environment --all")
	hl.exec_cmd("sleep 1 && /usr/libexec/xdg-desktop-portal-hyprland & /usr/libexec/xdg-desktop-portal")
	hl.exec_cmd("awww-daemon")
	hl.exec_cmd("dunst -config $HOME/.config/dunst/dunstrc")
	hl.exec_cmd("$HOME/.config/hypr/scripts/sw.sh")
	hl.exec_cmd("$HOME/.config/hypr/scripts/waylaunch.sh")
	hl.exec_cmd("gnome-keyring-daemon --start --components=ssh,secrets,pkcs11")
	hl.exec_cmd(defaults.terminal or "kitty", { workspace = "1" })
end)
